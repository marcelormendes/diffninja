#!/usr/bin/env node
// Regenerates src/languages/grammar-lock.ts: the exact tree-sitter grammar
// packages `diffninja grammars install` may download, with the registry's
// integrity hash of every tarball, direct or transitive.
//
// Why a lock and not "whatever is latest": the reviewer must never fetch code
// on its own, and when a person asks it to, the code has to be a fixed, vetted
// set. `npm ci` from this lock refuses any tarball whose hash differs.
//
// Run: node scripts/pin-grammars.mjs [--check]
//   (no flag)  rewrite src/languages/grammar-lock.ts from PINS below
//   --check    fail if the file on disk differs from a fresh resolution
//
// To move a pin: change the version below, run this, review the diff of the
// generated file (new transitive packages appear there), run
// `npm view <package>@<version> scripts maintainers` for anything new, and note
// it in the pull request. Grammars that ship no prebuilt binary (BUILD_ONLY) are
// pinned and hash-checked too, but their install script (a source build) runs
// only for `diffninja grammars install --build`.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const PINS = {
  "@tree-sitter-grammars/tree-sitter-lua": "0.2.0",
  "@tree-sitter-grammars/tree-sitter-zig": "1.1.2",
  "tree-sitter-bash": "0.25.1",
  "tree-sitter-c": "0.24.1",
  "tree-sitter-c-sharp": "0.23.1",
  "tree-sitter-cpp": "0.23.4",
  "tree-sitter-elixir": "0.3.5",
  "tree-sitter-go": "0.25.0",
  "tree-sitter-haskell": "0.23.1",
  "tree-sitter-java": "0.23.5",
  "tree-sitter-kotlin": "0.3.8",
  "tree-sitter-ocaml": "0.24.2",
  "tree-sitter-perl": "2.0.0",
  "tree-sitter-php": "0.24.2",
  "tree-sitter-python": "0.25.0",
  "tree-sitter-ruby": "0.23.1",
  "tree-sitter-rust": "0.24.0",
  "tree-sitter-scala": "0.24.0",
  "tree-sitter-solidity": "1.2.13",
  "tree-sitter-swift": "0.7.1",
};

/** Packages with no prebuilt binary: usable only after a source build, which needs a compiler. */
const BUILD_ONLY = ["tree-sitter-kotlin", "tree-sitter-perl"];

// Every dependency entry of the lock, root excepted, must carry both.
const lockSchema = z.object({
  packages: z.record(z.string(), z.object({ version: z.string().optional(), integrity: z.string().default(""), resolved: z.string().default("") }).passthrough()),
});

const OUTPUT = fileURLToPath(new URL("../src/languages/grammar-lock.ts", import.meta.url));
const ROOT = { name: "diffninja-grammar-cache", version: "1.0.0", private: true, dependencies: PINS };

const scratch = mkdtempSync(join(tmpdir(), "diffninja-pin-"));
try {
  writeFileSync(join(scratch, "package.json"), JSON.stringify(ROOT, null, 2));
  // An explicit registry: the lock records `resolved` URLs, and an ambient mirror would leak into them.
  execFileSync(process.platform === "win32" ? "npm.cmd" : "npm", [
    "install", "--package-lock-only", "--ignore-scripts", "--legacy-peer-deps", "--no-audit", "--no-fund",
    "--registry=https://registry.npmjs.org/",
  ], { cwd: scratch, stdio: "inherit", shell: process.platform === "win32" });
  const lock = JSON.parse(readFileSync(join(scratch, "package-lock.json"), "utf8"));
  const { packages } = lockSchema.parse(lock);
  for (const path of Object.keys(packages).filter((path) => path !== "")) {
    if (!packages[path].integrity.startsWith("sha512-")) throw new Error(`${path} has no sha512 integrity`);
    if (!packages[path].resolved.startsWith("https://registry.npmjs.org/")) throw new Error(`${path} does not resolve from registry.npmjs.org: ${packages[path].resolved}`);
  }
  for (const [name, version] of Object.entries(PINS)) {
    if (packages[`node_modules/${name}`]?.version !== version) throw new Error(`${name} did not resolve to the pinned ${version}`);
  }

  const source = [
    "// GENERATED by scripts/pin-grammars.mjs. Do not edit; change PINS there and rerun it.",
    "//",
    "// The tree-sitter grammars `diffninja grammars install` may download, with the",
    "// registry's integrity hash of every tarball (npm lockfile v3). Nothing outside",
    "// this file is ever installed on a reviewer's behalf.",
    "",
    "/** The grammar packages and the exact version of each. */",
    `export const GRAMMAR_PINS = ${JSON.stringify(PINS, null, 2)} as const;`,
    "",
    "/** Pinned packages that ship no prebuilt binary and load only after `grammars install --build`. */",
    `export const GRAMMAR_BUILD_ONLY = ${JSON.stringify(BUILD_ONLY)} as const;`,
    "",
    "/** The cache directory's package.json; its dependencies are GRAMMAR_PINS. */",
    `export const GRAMMAR_PACKAGE_JSON = ${JSON.stringify(ROOT, null, 2)} as const;`,
    "",
    "/** The cache directory's package-lock.json, exactly as npm resolved it. */",
    `export const GRAMMAR_PACKAGE_LOCK = ${JSON.stringify(lock, null, 2)} as const;`,
    "",
  ].join("\n");

  if (process.argv.includes("--check")) {
    if (readFileSync(OUTPUT, "utf8") !== source) throw new Error("src/languages/grammar-lock.ts is out of date; run node scripts/pin-grammars.mjs");
    console.log("grammar-lock.ts matches a fresh resolution.");
  } else {
    writeFileSync(OUTPUT, source);
    console.log(`wrote ${OUTPUT}: ${Object.keys(PINS).length} pinned grammars, ${Object.keys(lock.packages).length - 1} packages in the lock`);
  }
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
